"""Migration round trip on its own throwaway database, so the shared test DB stays at head."""

import asyncio
from collections.abc import Iterator

import asyncpg
import pytest
from alembic import command
from sqlalchemy import URL

from harvester.config import get_settings
from harvester.db import Base
from tests.conftest import (
    TEST_URL,
    alembic_config,
    asyncpg_dsn,
    drop_database,
    recreate_database,
)

ROUNDTRIP_URL = TEST_URL.set(database=f"{TEST_URL.database}_migrations")
PGVECTOR_REVISION = "0b91396a7850"


def public_tables(url: URL) -> set[str]:
    async def fetch() -> set[str]:
        conn = await asyncpg.connect(asyncpg_dsn(url))
        try:
            rows = await conn.fetch("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
            return {r["tablename"] for r in rows}
        finally:
            await conn.close()

    return asyncio.run(fetch())


@pytest.fixture
def roundtrip_db(monkeypatch: pytest.MonkeyPatch) -> Iterator[URL]:
    """Point alembic (via settings) at a fresh database for the duration of one test."""
    recreate_database(ROUNDTRIP_URL)
    monkeypatch.setenv("DATABASE_URL", ROUNDTRIP_URL.render_as_string(hide_password=False))
    get_settings.cache_clear()
    yield ROUNDTRIP_URL
    monkeypatch.undo()
    get_settings.cache_clear()
    drop_database(ROUNDTRIP_URL)


def test_upgrade_downgrade_upgrade_round_trip(roundtrip_db: URL) -> None:  # covers: AC-1
    cfg = alembic_config()
    model_tables = {t.name for t in Base.metadata.sorted_tables}

    command.upgrade(cfg, PGVECTOR_REVISION)
    command.upgrade(cfg, "head")
    assert public_tables(roundtrip_db) == model_tables | {"alembic_version"}
    assert len(model_tables) == 16

    command.downgrade(cfg, PGVECTOR_REVISION)
    assert public_tables(roundtrip_db) == {"alembic_version"}

    command.upgrade(cfg, "head")
    assert public_tables(roundtrip_db) == model_tables | {"alembic_version"}


